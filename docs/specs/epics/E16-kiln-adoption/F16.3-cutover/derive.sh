#!/usr/bin/env bash
# S16.3.12: give pykit's spec pages kiln's derived-region fences and fill them; write the result as a patch.
# Usage, from the repository root: bash <this file> <patch-path>
# Overlays steps 01 to 04, converts, generates, formats, and stops. It resets and cleans nothing.
set -euo pipefail
PATCH="${1:?usage: derive.sh <patch-path>}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

test "$(git branch --show-current)" = feature/kiln-cutover
test -z "$(git status --porcelain)"

for step in 01-managed 02-config 03-blocks 04-seeded; do
  bash "$HERE/steps/$step.sh" >/dev/null
done
git status --porcelain >"$PATCH.overlay"
task setup
# The root pyproject gains google-yamlfmt only in step 6, and the next `task setup` removes it.
uv pip install google-yamlfmt==0.21.0

# Fences first: kiln fills only the fences it finds, and without the board fence it
# skips every spec region. Hand-written feature rows that a feature file now derives
# are removed; the removed rows are saved beside the patch.
python3 -I - "$PATCH.removed" <<'PY'
import pathlib
import re
import sys

removed_log = pathlib.Path(sys.argv[1])
docs = pathlib.Path("docs")
removed: list[str] = []


def convert_board() -> None:
    page = docs / "specs" / "index.md"
    text = page.read_text()
    if "<!-- board:start -->" not in text:
        return
    sentence = (
        "the Releases and\nBacklog sections below are generated by `docs/_update_board.sh` from the epic\n"
        "and feature pages, and must not be edited by hand."
    )
    assert text.count(sentence) == 1, page
    text = text.replace(
        sentence,
        "the Releases and\nBacklog sections below are derived from the epic, feature and release pages by\n"
        "`task docs:generate`; never edit inside their fence.",
    )
    text = text.replace("<!-- board:start -->", "<!-- BEGIN derived board -->")
    text = text.replace("<!-- board:end -->", "<!-- END derived board -->")
    text = text.replace("<!-- generated by docs/_update_board.sh: do not edit -->\n\n", "")
    page.write_text(text)


def convert_releases() -> None:
    for page in sorted((docs / "releases").glob("release-*/index.md")):
        text = page.read_text()
        if "<!-- scope:start -->" not in text:
            continue
        text = text.replace("<!-- scope:start -->", "<!-- BEGIN derived scope -->")
        text = text.replace("<!-- scope:end -->", "<!-- END derived scope -->")
        text = text.replace("<!-- generated by docs/_update_board.sh: do not edit -->\n\n", "")
        page.write_text(text)


def feature_table(lines: list[str]) -> tuple[int, int] | None:
    """The line span of the first table outside code that has a feature ID in a row."""
    in_code = False
    start = None
    spans: list[tuple[int, int]] = []
    for n, line in enumerate(lines + [""]):
        if line.lstrip().startswith("```"):
            in_code = not in_code
        if not in_code and line.startswith("|"):
            if start is None:
                start = n
        elif start is not None:
            spans.append((start, n))
            start = None
    for a, b in spans:
        if any(re.search(r"F\d+\.\d+", row.split("|")[1]) for row in lines[a + 2 : b]):
            return a, b
    return None


def convert_epics() -> None:
    for index in sorted((docs / "specs" / "epics").glob("E*/index.md")):
        ids = {re.match(r"F\d+\.\d+", f.name).group(0) for f in index.parent.glob("F*.md")}
        if not ids:
            continue
        lines = index.read_text().splitlines()
        span = feature_table(lines)
        if span is None:
            continue
        a, b = span
        kept = [lines[a], lines[a + 1]]
        for row in lines[a + 2 : b]:
            found = re.search(r"F\d+\.\d+", row.split("|")[1])
            if found and found.group(0) in ids:
                removed.append(f"{index.as_posix()}: {row}")
            else:
                kept.append(row)
        if len(kept) == 2:
            kept = []
            if b < len(lines) and not lines[b].strip():
                b += 1
        lines[a:b] = kept
        index.write_text("\n".join(lines) + "\n")


convert_board()
convert_releases()
convert_epics()
removed_log.write_text("\n".join(removed) + ("\n" if removed else ""))
PY

# Generate until nothing changes: a second run must leave the tree as the first left it.
task docs:generate
task format
task docs:generate
before="$(git diff | shasum -a 256)"
task docs:generate
test "$(git diff | shasum -a 256)" = "$before" || { echo "docs:generate is not idempotent" >&2; exit 1; }

# Only Markdown under docs/ and packages/*/docs, and nothing on the overlay list.
sed 's/^...//' "$PATCH.overlay" >"$PATCH.overlay-paths"
paths=()
while IFS= read -r path; do
  paths+=("$path")
done < <(git diff --name-only -- 'docs/*.md' 'packages/*/docs/*.md' | grep -vxF -f "$PATCH.overlay-paths" || true)
rm "$PATCH.overlay-paths"
test "${#paths[@]}" -gt 0 || { echo "no spec page changed" >&2; exit 1; }

git diff -- "${paths[@]}" >"$PATCH"
printf '%s\n' "${paths[@]}"
echo "${#paths[@]} files in $PATCH; overlay paths in $PATCH.overlay; removed hand-written rows in $PATCH.removed"
